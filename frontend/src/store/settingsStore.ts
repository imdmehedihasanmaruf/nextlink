export type TranslationKey = keyof typeof translations.us

export function useTranslation() {
  const language = useSettingsStore((s) => s.language)
  
  // Normalize code
  let langKey = language as string
  if (langKey === 'en') langKey = 'us'
  if (langKey === 'bn') langKey = 'us' // Bangladesh removed per Req 21

  const currentDict = translations[langKey] || translations.us

  const t = (key: TranslationKey | string): string => {
    return currentDict[key] ?? translations.us[key] ?? key
  }

  return { t, language }
}
