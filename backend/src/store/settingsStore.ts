interface SettingsState {
  theme: Theme;
  themeColor: ThemeColor;
  fontSize: FontSize;
  language: Language;
  autoSave: boolean;
  deletedSidebarItems: string[];
  setTheme: (theme: Theme) => void;
  setThemeColor: (color: ThemeColor) => void;
  setFontSize: (size: FontSize) => void;
  setLanguage: (lang: Language) => void;
  setAutoSave: (val: boolean) => void;
  deleteSidebarItem: (key: string) => void;
  restoreSidebarItem: (key: string) => void;
  resetSidebarItems: () => void;
}

export const useSettingsStore = create<SettingsState>()(
  persist(
    (set, get) => ({
      theme: 'light',
      themeColor: 'blue',
      fontSize: 'md',
      language: 'us',
      autoSave: true,
      deletedSidebarItems: [],
      setTheme: (theme) => set({ theme }),
      setThemeColor: (themeColor) => set({ themeColor }),
      setFontSize: (fontSize) => set({ fontSize }),
      setLanguage: (language) => set({ language }),
      setAutoSave: (autoSave) => set({ autoSave }),
      deleteSidebarItem: (key) =>
        set((state) => ({
          deletedSidebarItems: (state.deletedSidebarItems || []).includes(key)
            ? state.deletedSidebarItems
            : [...(state.deletedSidebarItems || []), key],
        })),
      restoreSidebarItem: (key) =>
        set((state) => ({
          deletedSidebarItems: (state.deletedSidebarItems || []).filter((k) => k !== key),
        })),
      resetSidebarItems: () => set({ deletedSidebarItems: [] }),
    }),
    {
      name: 'nextlink-admin-settings',
    }
  )
);

export function useAdminTranslation() {
  const language = useSettingsStore((s) => s.language);
  const t = (key: string, fallback?: string): string => {
    return translations[language]?.[key] || translations['us']?.[key] || fallback || key;
  };
  return { t, language };
}
